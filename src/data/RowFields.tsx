import { useState } from 'react';
import type { Column, Row } from './types';

const canUseDefault = (column: Column) => /auto_increment/i.test(column.extra) || column.defaultValue !== null;
const insertMode = (column: Column) => canUseDefault(column) ? 'default' : column.nullable ? 'null' : 'value';
// Match the visible initial fields even when Save is clicked without editing them.
export function initialInsertValues(columns: Column[]): Row {
  return Object.fromEntries(columns.filter(c => !c.generated && !c.binary && !canUseDefault(c)).map(c => [c.name, c.nullable ? null : '']));
}

export default function RowFields({ columns, original, onChange }: { columns: Column[]; original?: Row; onChange: (row: Row) => void }) {
  const [fields, setFields] = useState(() => Object.fromEntries(columns.map(c => [c.name, { mode: original ? (original[c.name] === null ? 'null' : 'value') : insertMode(c), value: original?.[c.name] ?? '' }])));
  function change(name: string, field: { mode: string; value: string }) {
    const next = { ...fields, [name]: field }; setFields(next);
    const values: Row = {};
    for (const c of columns) if (!c.generated && !c.binary && next[c.name].mode !== 'default') values[c.name] = next[c.name].mode === 'null' ? null : next[c.name].value;
    onChange(values);
  }
  return <div className="db-row-fields">{columns.map(c => <div key={c.name} className="db-row-field"><label htmlFor={`row-${c.name}`}>{c.name}<small>{c.type}{c.columnKey === 'PRI' ? ' · primary key' : ''}{c.generated || c.binary ? ' · read-only' : ''}</small></label>
    {c.generated || c.binary ? <code>{original?.[c.name] ?? 'Generated by MySQL'}</code> : <>
      <select aria-label={`${c.name} value mode`} value={fields[c.name].mode} onChange={e => change(c.name, { ...fields[c.name], mode: e.target.value })}>{!original && canUseDefault(c) && <option value="default">{/auto_increment/i.test(c.extra) ? 'Auto' : 'Use default'}</option>}<option value="value">Value</option>{c.nullable && <option value="null">NULL</option>}</select>
      <textarea id={`row-${c.name}`} aria-label={`${c.name} value`} rows={2} disabled={fields[c.name].mode !== 'value'} value={fields[c.name].value} onChange={e => change(c.name, { ...fields[c.name], value: e.target.value })} placeholder={fields[c.name].mode === 'value' ? 'Empty text is an empty string' : fields[c.name].mode === 'null' ? 'SQL NULL' : 'Let MySQL supply this value'} />
    </>}
  </div>)}</div>;
}
